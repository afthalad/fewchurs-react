// Writes the package's own version into a generated source file, so SDK_VERSION is never
// kept in step by hand. Each package runs this before tsup; CI fails if the result differs
// from what is committed, which is what stops a release from shipping a stale SDK header.
//
//   node ../../tools/stamp-version.mjs src/client/version.ts
//
// The path is relative to the package directory the script is run from.

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const target = process.argv[2];
if (!target) {
  console.error("Usage: node tools/stamp-version.mjs <output-path>");
  process.exit(1);
}

const { name, version } = JSON.parse(readFileSync(resolve("package.json"), "utf8"));
const contents = `// Generated by tools/stamp-version.mjs from ${name}'s package.json. Do not edit by hand.
export const SDK_VERSION = ${JSON.stringify(version)};
`;

const path = resolve(target);
let current = null;
try {
  current = readFileSync(path, "utf8");
} catch {
  // The file has not been generated yet.
}

if (current !== contents) {
  writeFileSync(path, contents);
  console.log(`[stamp-version] ${name}@${version} -> ${target}`);
}
